"""Extract a compact flight graph from Lodestar's MIT-licensed TravelData.lua.
Usage: python3 tools/build_light_beacons_data.py /path/to/TravelData.lua
Only data is parsed; source Lua is never executed. See the bundled credits.
"""
from pathlib import Path
import hashlib, re, sys
src = Path(sys.argv[1]).read_text()
nodes = src.split('\tnodes = {', 1)[1].split('\tflights = {', 1)[0]
flights = src.split('\tflights = {', 1)[1].split('\tships = {', 1)[0]
ships = src.split('\tships = {', 1)[1].split('\ttram = {', 1)[0]
out = ['-- Flight facts derived from Lodestar, MIT (see ThirdParty/Lodestar-LICENSE.txt).',
       '-- Source client: Forever 1.60.1.70245. Times are estimates, not measured ETAs.',
       '-- World axes: x=north, y=west. Character discovery is checked at runtime.',
       'local _, B = ...', 'B.TravelData = { nodes = {']
ids=set()
for line in nodes.splitlines():
    match=re.match(r'\s*\[(\d+)\] = \{ n = "([^"]+)"',line)
    if match and 'z = nil' not in line and int(match[1]) not in (62,63,84,85,86,87):
        ids.add(int(match[1])); out.append(line.strip())
out.append('}, flights = {')
current=None; rows={}
for line in flights.splitlines():
    m=re.match(r'^\t\t\[(\d+)\] = \{',line)
    if m: current=int(m[1]);continue
    m=re.match(r'^\t\t\t\[(\d+)\] = \{ s = (\d+)',line)
    if m and current in ids and int(m[1]) in ids:
        rows.setdefault(current,[]).append(f'[{m[1]}]={m[2]}')
for a,row in sorted(rows.items()): out.append(f'[{a}]={{'+','.join(row)+'},')
out.append('}, ships = {')
ship_count=0
for line in ships.splitlines():
    m=re.match(r'\s*\{ id = (\d+),',line)
    if m and int(m[1]) != 295: # Superseded by Forever's Menethil/Southshore/Auberdine loop.
        clean=line.split(', p = {',1)[0]+' },'
        out.append(clean.strip()); ship_count+=1
out.append('} }\n')
root=Path(__file__).resolve().parents[1]/'LightTheBeacons'
(root/'TravelData.lua').write_text('\n'.join(out))
(root/'ThirdParty'/'TravelData-source.txt').write_text(
    'Data source: https://github.com/danielcosta42/lodestar/blob/main/TravelData.lua\n'
    'Copyright (c) 2026 Daniel Costa (danielcosta42), MIT License.\n'
    'Original flight/transport facts: Blizzard client DB2, via wago.tools.\n'
    'Retrieved 2026-11-09 (America/Vancouver).\n'
    f'Source SHA-256: {hashlib.sha256(src.encode()).hexdigest()}\n'
    'Changes: retained nodes, directed flight-time estimates and transport stops; removed\n'
    'route polylines, services, class-only/special nodes, and obsolete ship path 295.\n'
    'Generated by tools/build_light_beacons_data.py. Game data belongs to Blizzard.\n')
print(f'{len(ids)} flight points, {sum(map(len,rows.values()))} directed flights, {ship_count} transport routes')
